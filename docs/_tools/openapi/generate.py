SUMMARIES: dict[tuple[str, str], str] = {}


def documented_operations(spec_dir: Path) -> tuple[dict[tuple[str, str], str], dict[str, tuple[str, str]]]:
    """Reads the hand-written `paths:` entries: {(normalised path, METHOD): spec path}, {norm path: (path, file)}"""
    import yaml  # pylint: disable=import-outside-toplevel
    root = (spec_dir / 'openapi.yaml').read_text(encoding='utf-8')
    root = strip_block(root, BEGIN_PATHS, END_PATHS)
    data = yaml.safe_load(root)
    ops: dict[tuple[str, str], str] = {}
    files: dict[str, tuple[str, str]] = {}
    for path, item in (data.get('paths') or {}).items():
        target = item
        if isinstance(item, dict) and '$ref' in item:
            file_rel = item['$ref']
            files[norm_path(path)] = (path, file_rel)
            text = strip_block((spec_dir / file_rel).read_text(encoding='utf-8'), BEGIN_OPS, END_OPS)
            target = yaml.safe_load(text) or {}
        for method in target:
            if method.lower() in HTTP_METHODS:
                ops[(norm_path(path), method.upper())] = path
                SUMMARIES[(norm_path(path), method.upper())] = str((target[method] or {}).get('summary', ''))
    return ops, files


def strip_block(text: str, begin: str, end: str) -> str:
    """Removes a generated block (markers included)"""
    pattern = re.compile(rf'^[ \t]*{re.escape(begin)}.*?^[ \t]*{re.escape(end)}[^\n]*\n?', re.S | re.M)
    return pattern.sub('', text)


def operation_ids(spec_dir: Path) -> set[str]:
    ids = set()
    for file in (spec_dir / 'paths').rglob('*.yaml'):
        text = file.read_text(encoding='utf-8')
        if text.startswith(GENERATED_HEADER):
            continue
        text = strip_block(text, BEGIN_OPS, END_OPS)
        ids.update(re.findall(r'^\s*operationId:\s*["\']?([\w-]+)', text, re.M))
    return ids


def dump_yaml(data: Any) -> str:
    import yaml  # pylint: disable=import-outside-toplevel

    class Dumper(yaml.SafeDumper):  # pylint: disable=too-many-ancestors
        def increase_indent(self, flow: bool = False, indentless: bool = False) -> Any:
            return super().increase_indent(flow, False)

    def str_presenter(dumper: Any, value: str) -> Any:
        if '\n' in value:
            return dumper.represent_scalar('tag:yaml.org,2002:str', value, style='|')
        return dumper.represent_scalar('tag:yaml.org,2002:str', value)

    Dumper.add_representer(str, str_presenter)
    return yaml.dump(data, Dumper=Dumper, sort_keys=False, indent=4, width=120, allow_unicode=True)


def slug(path: str, area_prefix: str) -> str:
    rest = path[len(area_prefix.rstrip('/')):].strip('/')
    base = area_prefix.strip('/').split('/')[-1].replace('_', '-')
    parts = [base]
    for seg in [s for s in rest.split('/') if s]:
        if seg.startswith('{'):
            parts.append('by-' + seg.strip('{}').replace('_', '-'))
        else:
            parts.append(re.sub(r'[^a-z0-9]+', '-', seg.lower()).strip('-'))
    return '-'.join(p for p in parts if p)


def replace_block(text: str, begin: str, end: str, body: str, anchor: str, indent: str) -> str:
    """Replaces the block between the markers, or inserts it after `anchor`'s section (before the next top key)"""
    block = f'{indent}{begin}\n{body}{indent}{end}\n'
    pattern = re.compile(rf'^[ \t]*{re.escape(begin)}.*?^[ \t]*{re.escape(end)}[^\n]*\n', re.S | re.M)
    if pattern.search(text):
        return pattern.sub(lambda _m: block, text, count=1)
    lines = text.splitlines(keepends=True)
    start = next(i for i, line in enumerate(lines) if line.rstrip() == anchor)
    end_index = len(lines)
    for i in range(start + 1, len(lines)):
        if lines[i].strip() and not lines[i].startswith((' ', '\t', '#')):
            end_index = i
            break
    while end_index > start + 1 and not lines[end_index - 1].strip():
        end_index -= 1
    return ''.join(lines[:end_index]) + block + ''.join(lines[end_index:])


def main() -> None:  # pylint: disable=too-many-locals,too-many-branches,too-many-statements
    if len(sys.argv) > 1 and sys.argv[1] == '--_extract':
        code_root, mode, out = sys.argv[2], sys.argv[3], sys.argv[4]
        records = extract(code_root, mode, '--_routes-only' in sys.argv)
        Path(out).write_text(json.dumps(records, default=str), encoding='utf-8')
        return

    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--code-root', required=True, help='DataGerry checkout whose REST API is documented')
    parser.add_argument('--previous-root', help='checkout of the previous release: newer operations get x-since')
    parser.add_argument('--spec-dir', default=str(HERE.parent.parent / 'source' / 'api_docs'))
    parser.add_argument('--config', default=str(HERE / 'config.yaml'))
    parser.add_argument('--python', default=sys.executable, help='interpreter with the backend requirements')
    parser.add_argument('--dry-run', action='store_true', help='report only, write nothing')
    parser.add_argument('--report', help='write the extraction and decisions as JSON to this file')
    args = parser.parse_args()

    spec_dir = Path(args.spec_dir).resolve()
    cfg = Config(Path(args.config))
    code_root = str(Path(args.code_root).resolve())

    merged: dict[tuple[str, str], dict[str, Any]] = {}
    modes: dict[tuple[str, str], set[str]] = collections.defaultdict(set)
    for mode in ('cloud', 'onprem'):
        for rec in run_extraction(args.python, code_root, mode, False):
            key = (rec['rule'], rec['method'])
            merged.setdefault(key, rec)
            modes[key].add(mode)
    previous: set[tuple[str, str]] | None = None
    if args.previous_root:
        previous = set()
        for mode in ('cloud', 'onprem'):
            for rec in run_extraction(args.python, str(Path(args.previous_root).resolve()), mode, True):
                previous.add((norm_path(rec['rule']), rec['method']))

    documented, documented_files = documented_operations(spec_dir)
    code_norm = {(norm_path(rule), method) for rule, method in merged}

    # ---- clean the previous run ------------------------------------------------------------------------------- #
    if not args.dry_run:
        for file in (spec_dir / 'paths').rglob('*.yaml'):
            text = file.read_text(encoding='utf-8')
            if text.startswith(GENERATED_HEADER):
                file.unlink()
            elif BEGIN_OPS in text:
                file.write_text(strip_block(text, BEGIN_OPS, END_OPS).rstrip('\n') + '\n', encoding='utf-8')
        for directory in sorted((spec_dir / 'paths').rglob('*'), reverse=True):
            if directory.is_dir() and not any(directory.iterdir()):
                directory.rmdir()

    op_ids = operation_ids(spec_dir)
    excluded: list[tuple[str, str, str]] = []
    new_paths: dict[str, dict[str, Any]] = collections.OrderedDict()   # spec path -> {file, ops}
    appended: dict[str, dict[str, Any]] = collections.defaultdict(dict)  # file -> {method: op}
    used_tags: dict[str, dict[str, Any]] = {}
    report: list[dict[str, Any]] = []
    mismatches: list[str] = []

    def sort_key(key: tuple[str, str]) -> tuple[str, int]:
        return (norm_path(key[0]), ['GET', 'POST', 'PUT', 'PATCH', 'DELETE'].index(key[1])
                if key[1] in ('GET', 'POST', 'PUT', 'PATCH', 'DELETE') else 9)

    by_function: dict[tuple[str, str, str], list[str]] = collections.defaultdict(list)
    for (rule, method), rec in merged.items():
        by_function[(rule, rec.get('module', ''), rec.get('function', ''))].append(method)

    for key in sorted(merged, key=sort_key):
        rec = merged[key]
        rec['shared_methods'] = sorted(by_function[(rec['rule'], rec.get('module', ''), rec.get('function', ''))])
        nkey = (norm_path(rec['rule']), rec['method'])
        path = openapi_path(rec['rule'])
        reason = cfg.exclusion_for(rec)
        labels = edition_labels(rec, modes[key])
        if not reason and not labels:
            reason = 'Reachable on no documented channel (not the cloud API key, not on-premise)'
        entry = {'method': rec['method'], 'path': path, 'api_level': rec.get('api_level'), 'right': rec.get('right'),
                 'modes': sorted(modes[key]), 'file': rec.get('file'), 'function': rec.get('function'),
                 'body_source': rec.get('body_source'), 'body_error': rec.get('body_error'),
                 'editions': labels, 'has_doc': bool(rec.get('doc'))}
        if reason:
            excluded.append((rec['method'], path, reason))
            report.append({**entry, 'status': 'excluded', 'reason': reason})
            continue
        if nkey in documented:
            report.append({**entry, 'status': 'documented'})
            summary = SUMMARIES.get(nkey, '')
            have = re.findall(r'\[(?:Cloud|OnPremise)\]', summary)
            if have != labels:
                mismatches.append(f"EDITIONS {rec['method']:6} {documented[nkey]}  -- spec says {' '.join(have) or '-'}"
                                  f", code says {' '.join(labels)} (api level {rec.get('api_level')})")
            continue
        area = cfg.area_for(path)
        is_new = previous is not None and nkey not in previous
        hand = documented_files.get(nkey[0])
        if hand:
            spec_path, file_rel = hand
            param_names = re.findall(r'\{([^}]+)\}', spec_path)
            rel = '../' * (file_rel.count('/') - 1)
            op = build_operation(rec, modes[key], cfg, rel, param_names, is_new, op_ids, area, spec_path)
            # A hand-written file keeps its own tags; the generated operation follows the first one
            appended[file_rel][rec['method'].lower()] = op
            report.append({**entry, 'status': 'appended', 'target': file_rel})
        else:
            # Flask tells `/x/<int:id>` from `/x/<string:name>` by the converter, OpenAPI cannot: such routes share
            # one path item, named after the first; the parameter keeps its own type and description
            spec_path = next((p for p in new_paths if norm_path(p) == norm_path(path) and p != path), path)
            if spec_path not in new_paths:
                base = slug(spec_path, area['prefix'])
                file_rel = f"./paths/{area['dir']}/{base}.yaml"
                while (spec_dir / file_rel).exists() or any(v['file'] == file_rel for v in new_paths.values()):
                    file_rel = file_rel[:-5] + '-gen.yaml'
                new_paths[spec_path] = {'file': file_rel, 'ops': {}}
            file_rel = new_paths[spec_path]['file']
            rel = '../' * (file_rel.count('/') - 1)
            names = re.findall(r'\{([^}]+)\}', spec_path) if spec_path != path else None
            op = build_operation(rec, modes[key], cfg, rel, names, is_new, op_ids, area, spec_path)
            new_paths[spec_path]['ops'][rec['method'].lower()] = op
            report.append({**entry, 'status': 'generated', 'target': file_rel})
        used_tags[area['tag']] = area

    stale = sorted(k for k in documented if k not in code_norm)

    # ---- report ------------------------------------------------------------------------------------------------ #
    counts = collections.Counter(r['status'] for r in report)
    print(f"operations in code: {len(merged)}  documented by hand: {counts['documented']}  "
          f"generated: {counts['generated']} (new files) + {counts['appended']} (appended to hand-written files)  "
          f"excluded: {counts['excluded']}")
    for method, path, reason in excluded:
        print(f'EXCLUDED {method:6} {path}  -- {reason}')
    for path, method in stale:
        print(f'STALE    {method:6} {documented[(path, method)]}  -- documented but not in the code any more')
    for line in mismatches:
        print(line)
    for r in report:
        if r['status'] in ('generated', 'appended') and not r['has_doc']:
            print(f"NO-DOCSTRING {r['method']:6} {r['path']}  ({r['file']})")
    for r in report:
        if r.get('body_error'):
            print(f"NO-SCHEMA {r['method']:6} {r['path']}  -- {r['body_error']}")
    if args.report:
        Path(args.report).write_text(json.dumps({'operations': report, 'records': [
            {k: v for k, v in rec.items() if k != 'doc'} for rec in merged.values()]}, indent=1, default=str),
            encoding='utf-8')
    if args.dry_run:
        return

    # ---- write ------------------------------------------------------------------------------------------------- #
    for spec_path, info in new_paths.items():
        target = spec_dir / info['file']
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(GENERATED_HEADER + f'\n# {spec_path}\n\n' + dump_yaml(info['ops']), encoding='utf-8')
    for file_rel, ops in appended.items():
        target = spec_dir / file_rel
        text = target.read_text(encoding='utf-8').rstrip('\n') + '\n\n'
        text += f'{BEGIN_OPS}\n{GENERATED_HEADER}\n\n' + dump_yaml(ops) + f'{END_OPS}\n'
        target.write_text(text, encoding='utf-8')

    root_file = spec_dir / 'openapi.yaml'
    root = root_file.read_text(encoding='utf-8')
    path_lines = ''.join(f'    {p}:\n        $ref: "{info["file"]}"\n' for p, info in new_paths.items())
    root = replace_block(root, BEGIN_PATHS, END_PATHS, path_lines, 'paths:', '    ')
    import yaml  # pylint: disable=import-outside-toplevel
    declared = {t['name'] for t in (yaml.safe_load(strip_block(root, BEGIN_TAGS, END_TAGS)).get('tags') or [])}
    tag_lines = ''
    for area in cfg.areas:
        if area['tag'] in used_tags and area['tag'] not in declared:
            declared.add(area['tag'])
            tag_lines += f"    - name: {json.dumps(area['tag'])}\n      description: {json.dumps(area['description'])}\n"
    for name, area in used_tags.items():
        if name not in declared:
            declared.add(name)
            tag_lines += f"    - name: {json.dumps(name)}\n      description: {json.dumps(area['description'])}\n"
    root = replace_block(root, BEGIN_TAGS, END_TAGS, tag_lines, 'tags:', '    ')
    root_file.write_text(root, encoding='utf-8')
    print(f'wrote {len(new_paths)} path files, appended to {len(appended)} hand-written files, '
          f'{tag_lines.count("- name:")} generated tags')


if __name__ == '__main__':
    main()
