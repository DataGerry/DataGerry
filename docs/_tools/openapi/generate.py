def _jsonable(value: Any) -> Any:
    """Returns `value` if it survives JSON, its `.value` for an enum, else None"""
    if hasattr(value, 'value') and not isinstance(value, (dict, list, str, int, float, bool)):
        value = value.value
    try:
        json.dumps(value)
        return value
    except (TypeError, ValueError):
        return None


def cerberus_to_json_schema(rules: Any, depth: int = 0) -> dict[str, Any]:
    """Converts one Cerberus field rule set to a JSON schema (OpenAPI 3.0 flavour)"""
    if not isinstance(rules, dict) or depth > 12:
        return {}
    out: dict[str, Any] = {}
    types = rules.get('type')
    types = list(types) if isinstance(types, (list, tuple)) else ([types] if types else [])
    mapped = [dict(CERBERUS_TYPES.get(t, {})) for t in types]
    mapped = [m for m in mapped if m]
    base_type = mapped[0]['type'] if len(mapped) == 1 else None
    if len(mapped) == 1:
        out.update(mapped[0])
    elif len(mapped) > 1:
        out['oneOf'] = mapped
    sub = rules.get('schema')
    if isinstance(sub, dict) and sub:
        if base_type == 'array' or (base_type is None and 'type' in sub and isinstance(sub.get('type'), (str, list))):
            out.setdefault('type', 'array')
            out['items'] = cerberus_to_json_schema(sub, depth + 1)
        else:
            out.setdefault('type', 'object')
            out.update(cerberus_object(sub, depth + 1))
    if base_type == 'array' and 'items' not in out:
        out['items'] = {}
    values = rules.get('valuesrules') or rules.get('valueschema')
    if isinstance(values, dict):
        out.setdefault('type', 'object')
        out['additionalProperties'] = cerberus_to_json_schema(values, depth + 1) or True
    elif base_type == 'object' and 'properties' not in out:
        out['additionalProperties'] = True
    if rules.get('nullable') and 'type' in out:  # 3.0: nullable needs a type
        out['nullable'] = True
    allowed = rules.get('allowed')
    if isinstance(allowed, (list, tuple, set)) and allowed:
        enum = [v for v in (_jsonable(a) for a in allowed) if v is not None]
        if base_type == 'array':
            out['items'] = {**out.get('items', {}), 'enum': enum}
        elif enum:
            out['enum'] = enum
    for key, str_key, list_key in (('minlength', 'minLength', 'minItems'), ('maxlength', 'maxLength', 'maxItems')):
        if isinstance(rules.get(key), int):
            out[list_key if base_type == 'array' else str_key] = rules[key]
    if base_type == 'string' and rules.get('empty') is False and 'minLength' not in out:
        out['minLength'] = 1
    for key, target in (('min', 'minimum'), ('max', 'maximum')):
        if isinstance(rules.get(key), (int, float)) and not isinstance(rules.get(key), bool):
            out[target] = rules[key]
    if isinstance(rules.get('regex'), str):
        out['pattern'] = rules['regex']
    if 'default' in rules and not callable(rules['default']):
        default = _jsonable(rules['default'])
        if default is not None:
            out['default'] = default
    for key in ('anyof', 'oneof'):
        if isinstance(rules.get(key), (list, tuple)):
            alts = [cerberus_to_json_schema(alt, depth + 1) for alt in rules[key]]
            alts = [a for a in alts if a]
            if alts:
                out['anyOf' if key == 'anyof' else 'oneOf'] = alts
    if rules.get('readonly'):
        out['readOnly'] = True
    meta = rules.get('meta')
    if isinstance(meta, dict) and isinstance(meta.get('description'), str):
        out['description'] = meta['description']
    return out


def cerberus_object(schema: dict[str, Any], depth: int = 0) -> dict[str, Any]:
    """Converts a Cerberus document schema (field -> rules) to the properties/required of a JSON object schema"""
    props: dict[str, Any] = {}
    required: list[str] = []
    for name, rules in schema.items():
        props[str(_jsonable(name) or name)] = cerberus_to_json_schema(rules, depth)
        if isinstance(rules, dict) and rules.get('required'):
            required.append(str(_jsonable(name) or name))
    out: dict[str, Any] = {'properties': props}
    if required:
        out['required'] = required
    return out


class _Scanner(ast.NodeVisitor):
    """Collects what a view function (or a helper it calls) reads from the request and answers with"""

    def __init__(self, module_globals: dict[str, Any]) -> None:
        self.g = module_globals
        self.query: dict[str, dict[str, Any]] = {}
        self.files: list[str] = []
        self.form: list[str] = []
        self.json_body = False
        self.validators: list[ast.expr] = []
        self.responses: list[str] = []
        self.file_response = False
        self.edition_guard: str | None = None
        self.calls: list[ast.expr] = []

    def _eval(self, node: ast.expr) -> Any:
        try:
            return eval(compile(ast.Expression(node), '<expr>', 'eval'), dict(self.g))  # noqa: S307
        except Exception:  # pylint: disable=broad-except
            return None

    @staticmethod
    def _is_request_attr(node: ast.expr, attr: str) -> bool:
        return (isinstance(node, ast.Attribute) and node.attr == attr and isinstance(node.value, ast.Name)
                and REQUEST_NAME.fullmatch(node.value.id) is not None)

    def visit_Call(self, node: ast.Call) -> None:  # noqa: N802
        func = node.func
        if isinstance(func, ast.Attribute):
            if self._is_request_attr(func.value, 'args') and func.attr in ('get', 'getlist') and node.args:
                key = self._eval(node.args[0])
                if isinstance(key, str):
                    typ: dict[str, Any] = {'type': 'string'}
                    for kw in node.keywords:
                        if kw.arg == 'type' and isinstance(kw.value, ast.Name):
                            typ = {'int': {'type': 'integer'}, 'float': {'type': 'number'},
                                   'bool': {'type': 'boolean'}}.get(kw.value.id, typ)
                    if func.attr == 'getlist':
                        typ = {'type': 'array', 'items': typ}
                    self.query.setdefault(key, typ)
            if self._is_request_attr(func.value, 'files') and func.attr in ('get', 'getlist') and node.args:
                key = self._eval(node.args[0])
                if isinstance(key, str):
                    self.files.append(key)
            if self._is_request_attr(func.value, 'form') and func.attr in ('get', 'getlist') and node.args:
                key = self._eval(node.args[0])
                if isinstance(key, str):
                    self.form.append(key)
            if func.attr in ('get_json',) and isinstance(func.value, ast.Name) and REQUEST_NAME.fullmatch(func.value.id):
                self.json_body = True
        name = func.id if isinstance(func, ast.Name) else (func.attr if isinstance(func, ast.Attribute) else '')
        if name == 'Validator' and node.args:
            self.validators.append(node.args[0])
        # The upload helpers of route_utils: a file part, and a form part holding JSON
        if name in ('get_file_in_request', 'get_element_from_data_request') and node.args:
            key = self._eval(node.args[0])
            key = getattr(key, 'value', key)
            if isinstance(key, str):
                (self.files if name == 'get_file_in_request' else self.form).append(key)
        if name in RESPONSE_CLASSES:
            self.responses.append(name)
        if name in FILE_RESPONSE_CALLS:
            self.file_response = True
        self.calls.append(func)
        self.generic_visit(node)

    def visit_Subscript(self, node: ast.Subscript) -> None:  # noqa: N802
        for attr, bucket in (('files', self.files), ('form', self.form)):
            if self._is_request_attr(node.value, attr):
                key = self._eval(node.slice)
                if isinstance(key, str):
                    bucket.append(key)
        if self._is_request_attr(node.value, 'args'):
            key = self._eval(node.slice)
            if isinstance(key, str):
                self.query.setdefault(key, {'type': 'string'})
        self.generic_visit(node)

    def visit_Attribute(self, node: ast.Attribute) -> None:  # noqa: N802
        if self._is_request_attr(node, 'json'):
            self.json_body = True
        self.generic_visit(node)

    def visit_If(self, node: ast.If) -> None:  # noqa: N802
        """Spots the runtime edition guards: `if <cloud_mode>: abort(404)` and `if not is_hosted_cloud(): abort(404)`"""
        first = node.body[0] if node.body else None
        if (isinstance(first, ast.Expr) and isinstance(first.value, ast.Call)
                and isinstance(first.value.func, ast.Name) and first.value.func.id == 'abort'
                and first.value.args and isinstance(first.value.args[0], ast.Constant)
                and first.value.args[0].value == 404):
            test = ast.unparse(node.test)
            if 'cloud_mode' in test and not test.startswith('not '):
                self.edition_guard = 'onprem'
            elif test.startswith('not ') and ('is_hosted_cloud' in test or 'cloud_mode' in test):
                self.edition_guard = 'cloud'
        self.generic_visit(node)


_AST_CACHE: dict[str, Any] = {}


def _module_functions(module: Any) -> dict[str, list[ast.FunctionDef]]:
    path = getattr(module, '__file__', None)
    if not path:
        return {}
    if path not in _AST_CACHE:
        index: dict[str, list[ast.FunctionDef]] = collections.defaultdict(list)
        try:
            tree = ast.parse(Path(path).read_text(encoding='utf-8'))
        except (OSError, SyntaxError):
            tree = ast.Module(body=[], type_ignores=[])
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                index[node.name].append(node)
        _AST_CACHE[path] = index
    return _AST_CACHE[path]


def _scan(fn_node: ast.FunctionDef, module: Any, follow: int) -> _Scanner:
    """Scans a function body and, `follow` levels deep, the REST-layer helpers it calls"""
    scanner = _Scanner(vars(module))
    for stmt in fn_node.body:
        scanner.visit(stmt)
    scanner.helper_validators = []  # type: ignore[attr-defined]
    if follow <= 0:
        return scanner
    seen: set[int] = set()
    for func in scanner.calls:
        target = scanner._eval(func)  # pylint: disable=protected-access
        if not inspect.isfunction(target) or id(target) in seen:
            continue
        seen.add(id(target))
        mod_name = getattr(target, '__module__', '') or ''
        if not mod_name.startswith('cmdb.interface'):
            continue
        helper_module = sys.modules.get(mod_name)
        nodes = _module_functions(helper_module).get(target.__name__, []) if helper_module else []
        if len(nodes) != 1:
            continue
        sub = _scan(nodes[0], helper_module, follow=follow - 1)
        for key, typ in sub.query.items():
            scanner.query.setdefault(key, typ)
        scanner.files += sub.files
        scanner.form += sub.form
        scanner.responses += sub.responses
        scanner.file_response = scanner.file_response or sub.file_response
        scanner.edition_guard = scanner.edition_guard or sub.edition_guard
        for expr in sub.validators:
            scanner.helper_validators.append((expr, sub, target.__name__))  # type: ignore[attr-defined]
        scanner.helper_validators += sub.helper_validators  # type: ignore[attr-defined]
        if sub.json_body and target.__name__.startswith(('validate_', 'read_', 'parse_', 'get_')):
            scanner.json_body = scanner.json_body or sub.json_body
    return scanner


def _is_body_read(node: ast.AST) -> bool:
    """True for `request.get_json(...)` / `request.json`, also inside `... or {}`"""
    for sub in ast.walk(node):
        if isinstance(sub, ast.Attribute) and isinstance(sub.value, ast.Name) and REQUEST_NAME.fullmatch(sub.value.id) \
                and sub.attr in ('get_json', 'json'):
            return True
    return False


def _returns_body(func: Any) -> bool:
    """True for a REST-layer helper that reads the request body itself (e.g. `read_json_body()`)"""
    if not inspect.isfunction(func) or not (func.__module__ or '').startswith('cmdb.interface'):
        return False
    module = sys.modules.get(func.__module__)
    nodes = _module_functions(module).get(func.__name__, []) if module else []
    return len(nodes) == 1 and any(isinstance(n, ast.Return) and n.value is not None for n in ast.walk(nodes[0])) \
        and _is_body_read(nodes[0])


def payload_keys(fn_node: ast.FunctionDef, module: Any, names: set[str] | None, depth: int = 0,
                 bindings: dict[str, Any] | None = None) -> list[str]:
    """
    The keys an unvalidated JSON body is read with: `payload.get(KEY)`, `payload[KEY]`, `KEY in payload` on the
    variable the body was assigned to, followed into the REST/framework helpers the variable is passed to
    """
    scope = {**vars(module), **(bindings or {})}

    def ev_any(node: ast.expr) -> Any:
        try:
            return eval(compile(ast.Expression(node), '<key>', 'eval'), dict(scope))  # noqa: S307
        except Exception:  # pylint: disable=broad-except
            return None

    def ev(node: ast.expr) -> Any:
        value = ev_any(node)
        value = getattr(value, 'value', value)
        return value if isinstance(value, str) else None

    # `for key in GEOMETRY_KEYS: if key.value in payload` - the loop variable takes each value of the iterable
    loops: dict[str, list[Any]] = {}
    for node in ast.walk(fn_node):
        if isinstance(node, ast.For) and isinstance(node.target, ast.Name):
            values = ev_any(node.iter)
            if isinstance(values, (list, tuple, set, frozenset)) and len(values) < 100:
                loops.setdefault(node.target.id, []).extend(values)

    def ev_all(node: ast.expr) -> list[str]:
        single = ev(node)
        if single:
            return [single]
        used = {n.id for n in ast.walk(node) if isinstance(n, ast.Name)} & set(loops)
        if len(used) != 1:
            return []
        var = used.pop()
        found = []
        for value in loops[var]:
            scope[var] = value
            item = ev(node)
            if item:
                found.append(item)
        scope.pop(var, None)
        return found

    if names is None:
        names = set()
        for node in ast.walk(fn_node):
            if isinstance(node, (ast.Assign, ast.AnnAssign)) and node.value is not None and (
                    _is_body_read(node.value) or (isinstance(node.value, ast.Call) and not node.value.args
                                                  and _returns_body(ev_any(node.value.func)))):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                names.update(t.id for t in targets if isinstance(t, ast.Name))
    keys: list[str] = []
    for node in ast.walk(fn_node):
        found: list[str] = []
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr in ('get', 'pop') \
                and node.args and ((isinstance(node.func.value, ast.Name) and node.func.value.id in names)
                                   or (depth == 0 and _is_body_read(node.func.value)
                                       and not isinstance(node.func.value, ast.Name))):
            found = ev_all(node.args[0])
        elif isinstance(node, ast.Subscript) and isinstance(node.value, ast.Name) and node.value.id in names:
            found = ev_all(node.slice)
        elif isinstance(node, ast.Compare) and len(node.ops) == 1 and isinstance(node.ops[0], (ast.In, ast.NotIn)) \
                and isinstance(node.comparators[0], ast.Name) and node.comparators[0].id in names:
            found = ev_all(node.left)
        for key in found:
            if key not in keys:
                keys.append(key)
        if depth < 2 and isinstance(node, ast.Call):
            positions = [i for i, arg in enumerate(node.args) if isinstance(arg, ast.Name) and arg.id in names]
            kw_names = [kw.arg for kw in node.keywords if isinstance(kw.value, ast.Name) and kw.value.id in names]
            if not positions and not kw_names:
                continue
            try:
                target = eval(compile(ast.Expression(node.func), '<f>', 'eval'), dict(scope))  # noqa: S307
            except Exception:  # pylint: disable=broad-except
                continue
            if not inspect.isfunction(target) or not (target.__module__ or '').startswith('cmdb.'):
                continue
            helper_module = sys.modules.get(target.__module__)
            nodes = _module_functions(helper_module).get(target.__name__, []) if helper_module else []
            if len(nodes) != 1:
                continue
            params = [a.arg for a in nodes[0].args.args]
            sub_names = {params[i] for i in positions if i < len(params)} | {k for k in kw_names if k}
            sub_bindings = {params[i]: ev(arg) for i, arg in enumerate(node.args)
                            if i < len(params) and i not in positions and ev(arg)}
            for sub_key in payload_keys(nodes[0], helper_module, sub_names, depth + 1, sub_bindings):
                if sub_key not in keys:
                    keys.append(sub_key)
    return keys


def _parameter_class_fields(cls: Any) -> list[dict[str, Any]]:
    """Lists the query parameters a `parse_parameters(<class>)` adds on top of the collection parameters"""
    out = []
    try:
        sig = inspect.signature(cls.__init__)
    except (TypeError, ValueError):
        return out
    base_names = set()
    try:
        from cmdb.interface.rest_api.responses.response_parameters.collection_parameters import (  # noqa
            CollectionParameters)
        if issubclass(cls, CollectionParameters) and cls is not CollectionParameters:
            base_names = set(inspect.signature(CollectionParameters.__init__).parameters)
    except Exception:  # pylint: disable=broad-except
        pass
    doc_args = parse_docstring(inspect.getdoc(cls.__init__) or '')['args']
    for name, param in sig.parameters.items():
        if name in ('self', 'query_string', 'kwargs', 'args') or name in base_names:
            continue
        if param.kind in (param.VAR_KEYWORD, param.VAR_POSITIONAL):
            continue
        ann = str(param.annotation)
        schema = {'type': 'boolean'} if 'bool' in ann else ({'type': 'integer'} if 'int' in ann else {'type': 'string'})
        if name == 'acl':
            schema = {'type': 'string'}
        default = _jsonable(param.default) if param.default is not inspect.Parameter.empty else None
        if default is not None:
            schema['default'] = default
        out.append({'name': name, 'schema': schema, 'description': doc_args.get(name, '')})
    return out


def extract(code_root: str, mode: str, routes_only: bool) -> list[dict[str, Any]]:
    """Builds the REST app of `code_root` in `mode` and returns one record per (rule, method)"""
    sys.path.insert(0, code_root)
    import cmdb  # pylint: disable=import-outside-toplevel
    cmdb.__MODE__ = 'TESTING'
    cmdb.__CLOUD_MODE__ = mode == 'cloud'
    cmdb.__LOCAL_MODE__ = False
    from cmdb.interface.rest_api.init_rest_api import create_rest_api  # pylint: disable=import-outside-toplevel
    app = create_rest_api(None)

    records = []
    for rule in app.url_map.iter_rules():
        view = app.view_functions.get(rule.endpoint)
        methods = sorted(m for m in rule.methods if m not in ('HEAD', 'OPTIONS'))
        converters = {}
        for match in re.finditer(r'<(?:([a-zA-Z_]+)(?:\([^)]*\))?:)?([a-zA-Z_][a-zA-Z0-9_]*)>', rule.rule):
            converters[match.group(2)] = match.group(1) or 'default'
        base = {
            'rule': rule.rule, 'endpoint': rule.endpoint, 'converters': converters,
            'module': getattr(view, '__module__', ''), 'function': getattr(view, '__name__', ''),
        }
        if routes_only or view is None:
            for method in methods:
                records.append({**base, 'method': method})
            continue
        module = sys.modules.get(base['module'])
        nodes = _module_functions(module).get(base['function'], []) if module else []
        # The view whose route decorator names this rule (a function name can repeat across blueprints)
        fn_node = nodes[0] if len(nodes) == 1 else None
        if len(nodes) > 1:
            for node in nodes:
                if any(rule.rule.endswith(ast.literal_eval(d.args[0])) for d in node.decorator_list
                       if isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute) and d.func.attr == 'route'
                       and d.args and isinstance(d.args[0], ast.Constant)):
                    fn_node = node
                    break
        meta: dict[str, Any] = {
            'file': os.path.relpath(getattr(module, '__file__', '') or '', code_root),
            'line': fn_node.lineno if fn_node else None,
            'decorators': [], 'api_level': None, 'right': None, 'excepted': None, 'body_schema': None,
            'body_source': None, 'body_error': None, 'collection_parameters': False, 'parameter_fields': [],
            'request_parameters': False, 'request_body': False, 'query': {}, 'files': [], 'form': [],
            'json_body': False, 'responses': [], 'file_response': False,
            'doc': inspect.getdoc(view) or '',
        }
        scope = vars(module) if module else {}

        def ev(node: ast.expr) -> Any:
            try:
                return eval(compile(ast.Expression(node), '<decorator>', 'eval'), dict(scope))  # noqa: S307
            except Exception:  # pylint: disable=broad-except
                return None

        if fn_node is not None:
            for deco in fn_node.decorator_list:
                meta['decorators'].append(ast.unparse(deco))
                call = deco if isinstance(deco, ast.Call) else None
                func = call.func if call else deco
                name = func.attr if isinstance(func, ast.Attribute) else (func.id if isinstance(func, ast.Name) else '')
                kwargs = {kw.arg: kw.value for kw in call.keywords} if call else {}
                if name == 'verify_api_access':
                    level = kwargs.get('required_api_level')
                    meta['api_level'] = level.attr if isinstance(level, ast.Attribute) else 'NO_API'
                elif name == 'protect':
                    if 'right' in kwargs:
                        meta['right'] = _jsonable(ev(kwargs['right']))
                    if 'excepted' in kwargs:
                        meta['excepted'] = _jsonable(ev(kwargs['excepted']))
                elif name == 'validate' and call and call.args:
                    schema = ev(call.args[0])
                    meta['body_source'] = f'validate({ast.unparse(call.args[0])})'
                    if isinstance(schema, dict):
                        meta['body_schema'] = {'type': 'object', **cerberus_object(schema)}
                    else:
                        meta['body_error'] = f'could not resolve {ast.unparse(call.args[0])}'
                elif name == 'parse_collection_parameters':
                    meta['collection_parameters'] = True
                elif name == 'parse_parameters' and call and call.args:
                    cls = ev(call.args[0])
                    meta['collection_parameters'] = bool(cls) and any(
                        b.__name__ == 'CollectionParameters' for b in inspect.getmro(cls))
                    if cls is not None:
                        meta['parameter_fields'] = _parameter_class_fields(cls)
                elif name == 'parse_request_parameters':
                    meta['request_parameters'] = True
                elif name == 'parse_request_body':
                    meta['request_body'] = True

            scanner = _scan(fn_node, module, follow=2)
            meta['query'] = scanner.query
            meta['files'] = sorted(set(scanner.files))
            meta['form'] = sorted(set(scanner.form))
            meta['json_body'] = scanner.json_body
            meta['responses'] = list(dict.fromkeys(scanner.responses))
            meta['file_response'] = scanner.file_response
            meta['edition_guard'] = scanner.edition_guard
            meta['payload_keys'] = payload_keys(fn_node, module, None) if scanner.json_body else []
            if meta['body_schema'] is None and scanner.json_body and scanner.validators + scanner.helper_validators:
                candidates = [(expr, scanner, base['function']) for expr in scanner.validators]
                candidates += scanner.helper_validators
                for expr, sub_scanner, origin in candidates:
                    schema = sub_scanner._eval(expr)  # pylint: disable=protected-access
                    if isinstance(schema, dict) and schema and all(isinstance(v, dict) for v in schema.values()):
                        meta['body_schema'] = {'type': 'object', **cerberus_object(schema)}
                        meta['body_source'] = f'Validator({ast.unparse(expr)}) in {origin}'
                        break
        for method in methods:
            records.append({**base, **meta, 'method': method})
    return records


def run_extraction(python: str, code_root: str, mode: str, routes_only: bool) -> list[dict[str, Any]]:
    """Runs `extract` in a child process (each code root and mode needs a fresh interpreter)"""
    with tempfile.NamedTemporaryFile(suffix='.json', delete=False) as handle:
        out = handle.name
    cmd = [python, '-I', str(Path(__file__).resolve()), '--_extract', code_root, mode, out]
    if routes_only:
        cmd.append('--_routes-only')
    proc = subprocess.run(cmd, capture_output=True, text=True, check=False, cwd=tempfile.gettempdir())
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout + proc.stderr)
        raise SystemExit(f'extraction failed for {code_root} ({mode})')
    try:
        return json.loads(Path(out).read_text(encoding='utf-8'))
    finally:
        os.unlink(out)

