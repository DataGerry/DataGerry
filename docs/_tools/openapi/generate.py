def parse_docstring(doc: str) -> dict[str, Any]:
    """Splits a Google style docstring into summary, description paragraphs, args, returns and raises"""
    result: dict[str, Any] = {'summary': '', 'description': [], 'args': {}, 'returns': '', 'raises': ''}
    if not doc:
        return result
    lines = doc.splitlines()
    sections: dict[str, list[str]] = {'_': []}
    current = '_'
    header = re.compile(r'^([A-Z][A-Za-z ()]*?)\s*(\(.*\))?:\s*$')
    for line in lines:
        match = header.match(line)
        if match and not line.startswith(' ') and match.group(1).split()[0] in (
                'Args', 'Arguments', 'Returns', 'Return', 'Raises', 'Behavior', 'Behaviour', 'Example', 'Examples',
                'Note', 'Notes', 'Yields', 'Attributes', 'Errors', 'Response', 'Responses', 'Permissions'):
            current = match.group(1).split()[0]
            sections.setdefault(current, [])
            continue
        sections.setdefault(current, []).append(line)
    paragraphs = [p.strip() for p in re.split(r'\n\s*\n', '\n'.join(sections['_'])) if p.strip()]
    if paragraphs:
        result['summary'] = ' '.join(paragraphs[0].split())
        result['description'] = paragraphs[1:]
    arg_lines = sections.get('Args', []) + sections.get('Arguments', [])
    name = None
    for line in arg_lines:
        match = re.match(r'^\s{0,8}(\*{0,2}[A-Za-z_][A-Za-z0-9_]*)\s*(\([^)]*\))?\s*:\s*(.*)$', line)
        if match and (len(line) - len(line.lstrip())) <= 8 and (name is None or len(line) - len(line.lstrip()) <= 4):
            name = match.group(1).lstrip('*')
            result['args'][name] = match.group(3).strip()
        elif name and line.strip():
            result['args'][name] += ' ' + line.strip()
    result['returns'] = ' '.join(' '.join(sections.get('Returns', []) + sections.get('Return', [])).split())
    raises = sections.get('Raises', []) + sections.get('Errors', [])
    result['raises'] = textwrap.dedent('\n'.join(raises)).strip()
    return result


_VERB_FIXES = {'Is': 'Check whether', 'Has': 'Check whether'}
_METHODS = r'`{0,2}(?:GET|POST|PUT|PATCH|DELETE|HEAD)`{0,2}'
ROUTE_PHRASE = re.compile(rf'^(?:This\s+)?(?:(?:HTTP\s+)?{_METHODS}(?:\s*(?:/|,|and|or)\s*{_METHODS})*\s+)?'
                          r'(?:API\s+|REST\s+)?(?:route|endpoint)\b\s*(?:to|for|that|which)?\s*', re.I)
# "PUT/PATCH ``/rest/categories/<public_id>`` - update a CmdbCategory"
METHOD_PATH_PHRASE = re.compile(rf'^{_METHODS}(?:\s*/\s*{_METHODS})*\s+`*/\S+`*\s+[-:]\s+')
# Noun phrases a GET docstring starts with ("A page of rights ...", "The other edit logs ...")
NOUN_STARTS = ('A', 'An', 'The', 'One', 'All', 'Every', 'Logs', 'Object', 'What', 'Static')


def _gerund_to_imperative(word: str) -> str:
    stem = word[:-3]
    if re.search(r'([bdgmnprt])\1$', stem):
        return stem[:-1]
    if re.search(r'(at|iv|ov|uc|iz|ag|ur|id|ad|ar|ir|as|ol|ens|ers|ac|eas|ys|ash|lv|ev|ang|rg|ss)$', stem) \
            and stem not in ('start', 'export', 'import', 'report', 'edit', 'list', 'count', 'search', 'check',
                             'mount', 'add', 'pass'):
        return stem + 'e'
    return stem


def _third_person_to_imperative(word: str) -> str:
    if word.endswith('ies'):
        return word[:-3] + 'y'
    if re.search(r'(ches|shes|sses|xes|zes)$', word):
        return word[:-2]
    if word.endswith('s') and not word.endswith(('ss', 'us', 'is')):
        return word[:-1]
    return word


def imperative_summary(text: str, method: str, path: str) -> str:
    """Turns the first docstring sentence into a short imperative summary"""
    text = ' '.join(text.split()).strip()
    text = METHOD_PATH_PHRASE.sub('', text, count=1)
    text = ROUTE_PHRASE.sub('', text, count=1) if ROUTE_PHRASE.match(text) else text
    if not text:
        return f'{method.upper()} {path}'
    words = text.split(' ')
    first = words[0][:1].upper() + words[0][1:]
    if first in _VERB_FIXES:
        first = _VERB_FIXES[first]
    elif first in NOUN_STARTS and method == 'GET':
        first = 'Retrieve ' + first.lower()
    elif re.fullmatch(r'[A-Z][a-z]+ing', first) and len(first) > 5:
        first = _gerund_to_imperative(first.lower()).capitalize()
    elif re.fullmatch(r'[A-Z][a-z]+(?:-[a-z]+)?', first) and len(first) > 3 and first not in ('Bulk', 'This'):
        first = _third_person_to_imperative(first)
    words[0] = first
    text = ' '.join(words)
    text = re.sub(r'\b(?:Cmdb|Isms)(?=[A-Z])', '', text)
    text = re.sub(r'\b([aA]) (?=[AEIO][a-z])', r'\1n ', text)
    text = re.sub(r'\b([aA])n (?=U[a-z])', r'\1 ', text)
    text = text.replace('`', '')
    for sep in ('. ', ' - ', '; ', ' (', ': '):
        if len(text) > 90 and sep in text:
            text = text.split(sep)[0]
    if len(text) > 110:
        text = text[:107].rsplit(' ', 1)[0] + '...'
    return text.rstrip('.').rstrip()


def norm_path(path: str) -> str:
    """Normalises a Flask rule or an OpenAPI path for comparison"""
    path = re.sub(r'<(?:[a-zA-Z_]+(?:\([^)]*\))?:)?([a-zA-Z_][a-zA-Z0-9_]*)>', r'{\1}', path)
    path = re.sub(r'\{[^}]+\}', '{}', path)
    return path.rstrip('/') or '/'


def openapi_path(rule: str) -> str:
    return re.sub(r'<(?:[a-zA-Z_]+(?:\([^)]*\))?:)?([a-zA-Z_][a-zA-Z0-9_]*)>', r'{\1}', rule)


class Config:
    """The hand-maintained rules in config.yaml: areas, exclusions and per-operation overrides"""

    def __init__(self, path: Path) -> None:
        import yaml  # pylint: disable=import-outside-toplevel
        data = yaml.safe_load(path.read_text(encoding='utf-8')) or {}
        self.areas: list[dict[str, Any]] = data.get('areas', [])
        self.exclude: list[dict[str, Any]] = data.get('exclude', [])
        self.overrides: dict[str, dict[str, Any]] = data.get('overrides', {}) or {}
        self.components: dict[str, str] = data.get('result_components', {}) or {}
        self.level_notes: dict[str, str] = data.get('level_notes', {}) or {}

    def area_for(self, path: str) -> dict[str, Any]:
        best = None
        for area in self.areas:
            prefix = area['prefix'].rstrip('/')
            if path == prefix or path.startswith(prefix + '/'):
                if best is None or len(prefix) > len(best['prefix'].rstrip('/')):
                    best = area
        if best is None:
            seg = path.strip('/').split('/')[0] or 'root'
            best = {'prefix': '/' + seg, 'tag': seg.replace('_', ' ').title(), 'dir': seg,
                    'description': f'API Routes related to **{seg}**'}
        return best

    def override_for(self, method: str, path: str) -> dict[str, Any]:
        """The override of "<METHOD> <path>"; the path is compared normalised (parameter names, trailing slash)"""
        for key, value in self.overrides.items():
            o_method, _, o_path = key.partition(' ')
            if o_method.upper() == method and norm_path(o_path) == norm_path(path):
                return value or {}
        return {}

    def exclusion_for(self, record: dict[str, Any]) -> str | None:
        path = openapi_path(record['rule'])
        for rule in self.exclude:
            if 'path' in rule and not re.fullmatch(rule['path'], path):
                continue
            if 'method' in rule and rule['method'].upper() != record['method']:
                continue
            if 'api_level' in rule and rule['api_level'] != record.get('api_level'):
                continue
            if 'no_api_level' in rule and record.get('api_level') is not None:
                continue
            return rule['reason']
        return None


def schema_ref(spec_rel: str, component_file: str) -> dict[str, str]:
    return {'$ref': f'{spec_rel}components/{component_file}'}


def edition_labels(rec: dict[str, Any], modes: set[str]) -> list[str]:
    """
    [Cloud]: the route exists in cloud mode, has no on-premise-only guard and the cloud API key may reach it
    (ApiLevel ADMIN or NO_API). [OnPremise]: the route exists on-premise and has no hosted-cloud-only guard -
    on-premise `verify_api_access` checks no level, so LOCKED and SUPER_ADMIN routes are reachable with Basic auth
    """
    guard = rec.get('edition_guard')
    labels = []
    if 'cloud' in modes and guard != 'onprem' and rec.get('api_level') in ('ADMIN', 'NO_API'):
        labels.append('[Cloud]')
    if 'onprem' in modes and guard != 'cloud':
        labels.append('[OnPremise]')
    return labels


def build_operation(rec: dict[str, Any], modes: set[str], cfg: Config, rel: str, param_names: list[str] | None,
                    is_new: bool, op_ids: set[str], area: dict[str, Any], path: str) -> dict[str, Any]:
    """Builds one OpenAPI operation object from an extraction record"""
    override = cfg.override_for(rec["method"], path)
    doc = parse_docstring(rec.get('doc', ''))
    level = rec.get('api_level')
    editions = ' '.join(edition_labels(rec, modes)) or '[OnPremise]'
    summary = override.get('summary') or imperative_summary(doc['summary'], rec['method'], path)
    summary = f'{summary} {editions}'

    desc: list[str] = []
    right = rec.get('right')
    desc.append(f'Required User Right: **{right}**' if right else
                'Required User Right: **none** (any authenticated user)')
    desc.append('<br><hr><br>')
    body_text: list[str] = []
    if is_new:
        body_text.append(SINCE_TEXT)
    if rec.get('excepted'):
        pairs = ', '.join(f'`{k}` equals the path parameter `{v}`' for k, v in rec['excepted'].items())
        body_text.append(f'Also allowed without the right when the requesting user\'s {pairs}.')
    note = cfg.level_notes.get(level or '', '')
    if note and '[Cloud]' not in editions and 'cloud' in modes and rec.get('edition_guard') != 'onprem':
        body_text.append(note)
    if doc['summary'] and not ROUTE_PHRASE.match(doc['summary']) and not METHOD_PATH_PHRASE.match(doc['summary']):
        body_text.append(doc['summary'])
    if len(rec.get('shared_methods', [])) > 1:
        body_text.append(f"_{' and '.join(f'`{m}`' for m in rec['shared_methods'])} on this path run the same "
                         f"code._")
    body_text += doc['description']
    if override.get('description'):
        body_text.append(override['description'].strip())
    if doc['raises']:
        raises = re.sub(r'^\s*(?:HTTPException|werkzeug\.exceptions\.\w+|abort)\s*(?:\([^)]*\))?\s*:\s*', '',
                        doc['raises'], flags=re.M)
        body_text.append('**Errors:** ' + ' '.join(raises.split()))
    if rec.get('body_error'):
        body_text.append(f'_The request body schema could not be derived from the code ({rec["body_error"]})._')
    description = '\n'.join(desc) + '\n' + '\n\n'.join(body_text) + '\n'

    op: dict[str, Any] = {'tags': [area['tag']], 'summary': summary, 'description': description}
    if is_new:
        op['x-since'] = SINCE_VALUE

    parameters: list[dict[str, Any]] = []
    names = list(rec['converters'])
    for index, name in enumerate(names):
        spec_name = param_names[index] if param_names and index < len(param_names) else name
        schema = dict(CONVERTER_TYPES.get(rec['converters'][name], {'type': 'string'}))
        arg_desc = doc['args'].get(name) or f'The **{name}** of the resource'
        if spec_name != name:
            arg_desc += f' (the code calls this parameter `{name}`)'
        parameters.append({'name': spec_name, 'in': 'path', 'required': True, 'description': arg_desc,
                           'schema': schema})
    if rec.get('collection_parameters'):
        parameters.append({
            'name': 'CollectionParameters', 'in': 'query', 'required': False,
            'description': 'Parameters for filtering, limiting, sorting and pagination (`filter`, `limit`, `sort`, '
                           '`order`, `page`, `projection`)',
            'schema': schema_ref(rel, 'schemas/CollectionParameters.yaml'),
        })
    # Overridden query parameters come first and win over the derived ones of the same name
    for extra in override.get('query', []) or []:
        parameters.append({'name': extra['name'], 'in': 'query', 'required': False, **extra})
    seen = {p['name'] for p in parameters}
    for field in rec.get('parameter_fields', []):
        if field['name'] not in seen:
            seen.add(field['name'])
            parameters.append({'name': field['name'], 'in': 'query', 'required': False,
                               'description': field['description'] or f'The **{field["name"]}** query parameter',
                               'schema': field['schema']})
    for name, schema in sorted(rec.get('query', {}).items()):
        if name not in seen and not (rec.get('collection_parameters') and name in (
                'filter', 'limit', 'sort', 'order', 'page', 'projection')):
            seen.add(name)
            parameters.append({'name': name, 'in': 'query', 'required': False,
                               'description': doc['args'].get(name) or f'The **{name}** query parameter',
                               'schema': schema})
    if rec.get('request_parameters') and not rec.get('query') and not override.get('query'):
        op['description'] += ('\nThe query string is passed to the operation as a whole; see the description for '
                              'the parameters it reads.\n')
    if parameters:
        op['parameters'] = parameters

    op_id = override.get('operationId') or rec['function']
    if op_id in op_ids:
        op_id = f"{op_id}_{rec['method'].lower()}"
    suffix = 2
    while op_id in op_ids:
        op_id = f"{rec['function']}_{suffix}"
        suffix += 1
    op_ids.add(op_id)
    op['operationId'] = op_id

    body = build_request_body(rec, override)
    if body:
        op['requestBody'] = body
    op['responses'] = build_responses(rec, cfg, rel, path, doc, bool(body) or bool(parameters))
    return op


def build_request_body(rec: dict[str, Any], override: dict[str, Any]) -> dict[str, Any] | None:
    if override.get('requestBody'):
        return override['requestBody']
    if rec['method'] == 'GET':
        return None
    if rec.get('files') or rec.get('form'):
        props: dict[str, Any] = {name: {'type': 'string', 'format': 'binary'} for name in rec.get('files', [])}
        for name in rec.get('form', []):
            props.setdefault(name, {'type': 'string'})
        return {'required': True, 'content': {'multipart/form-data': {'schema': {'type': 'object',
                                                                                  'properties': props}}}}
    if rec.get('body_schema'):
        return {'required': True, 'content': {'application/json': {'schema': rec['body_schema']}}}
    if rec.get('request_body') or rec.get('json_body'):
        schema: dict[str, Any] = {
            'type': 'object', 'additionalProperties': True,
            'description': 'The operation reads the body without a declared schema; see the description.'}
        if rec.get('payload_keys'):
            schema['description'] = ('The operation reads the body without a declared schema. These are the keys '
                                     'it reads (types and rules: see the description).')
            schema['properties'] = {key: {} for key in rec['payload_keys']}
        return {'required': rec['method'] in ('POST', 'PUT', 'PATCH'),
                'content': {'application/json': {'schema': schema}}}
    return None


def build_responses(rec: dict[str, Any], cfg: Config, rel: str, path: str, doc: dict[str, Any],
                    has_input: bool) -> dict[str, Any]:
    """Success responses from the response classes the view uses, errors from components/responses.yaml"""
    component = None
    area_path = norm_path(path)
    for prefix, comp in cfg.components.items():
        if area_path in (prefix, prefix + '/{}'):
            component = comp
    item: dict[str, Any] = schema_ref(rel, f'schemas/{component}') if component else {
        'type': 'object', 'additionalProperties': True}
    envelope = {'$ref': f'{rel}components/schemas/ApiResponses.yaml#/ResponseEnvelope'}
    returns = re.sub(r'^\s*\w*(?:Response|Resp|dict\[[^]]*\]|list\[[^]]*\]|bool)\s*:\s*', '', doc['returns'])
    returns = returns[:1].upper() + returns[1:] if returns else 'The result of the operation'
    responses: dict[str, Any] = {}

    def add(code: str, description: str, props: dict[str, Any] | None = None, schema: Any = None) -> None:
        if code in responses:
            return
        if schema is None and props is not None:
            schema = {'allOf': [envelope, {'type': 'object', 'properties': props}]}
        entry: dict[str, Any] = {'description': description}
        if schema is not None:
            entry['content'] = {'application/json': {'schema': schema}}
        responses[code] = entry

    classes = rec.get('responses', [])
    if rec.get('file_response') or 'GridFsResponse' in classes:
        responses['200'] = {'description': returns, 'content': {'application/octet-stream': {
            'schema': {'type': 'string', 'format': 'binary'}}}}
    for cls in classes:
        if cls == 'GetSingleResponse':
            add('200', returns, {'result': item})
        elif cls == 'GetListResponse':
            add('200', returns, {'results': {'type': 'array', 'items': item}})
        elif cls == 'GetMultiResponse':
            add('200', returns, schema={'allOf': [
                {'$ref': f'{rel}components/schemas/ApiResponses.yaml#/MultiResponse'},
                {'type': 'object', 'properties': {'results': {'type': 'array', 'items': item}}}]})
        elif cls == 'InsertSingleResponse':
            add('201', returns, {'result_id': {'type': 'integer', 'description': 'The public_id of the new resource'},
                                 'raw': item})
        elif cls == 'UpdateSingleResponse':
            add('202', returns, {'result': item})
        elif cls == 'UpdateMultiResponse':
            add('202', returns, {'results': {'type': 'array', 'items': item},
                                 'failed': {'type': 'array', 'items': {'type': 'object', 'additionalProperties': True},
                                            'description': 'The entries that could not be updated'}})
        elif cls == 'DeleteSingleResponse':
            add('202', 'The deleted resource is returned under `raw`', {'raw': item})
            add('204', 'Deleted, nothing to report')
        elif cls in ('DefaultResponse', 'LoginResponse'):
            add('200', returns, schema={'description': 'The value itself (no response envelope)'})
    if not any(code.startswith('2') for code in responses):
        add('200', returns, schema={'description': 'The value itself (no response envelope)'})
    raises = doc['raises'] + ' ' + doc['returns']
    errors = {'400': 'BadRequest', '401': 'Unauthorized', '403': 'Forbidden', '404': 'NotFound',
              '500': 'InternalServerError'}
    wanted = {'401', '403', '500'}
    if has_input or re.search(r'\b400\b', raises):
        wanted.add('400')
    if '{' in path or re.search(r'\b404\b', raises):
        wanted.add('404')
    for code in sorted(wanted):
        responses[code] = {'$ref': f'{rel}components/responses.yaml#/{errors[code]}'}
    return responses

